def fetch_tag_frequencies(session):
    """태그별 빈도 집계"""
    result = session.run("""
        MATCH (q:QA)
        WHERE q.tags IS NOT NULL AND size(q.tags) > 0
        UNWIND q.tags AS tag
        RETURN tag, count(*) AS freq
        ORDER BY freq DESC
    """)
    return {r["tag"]: r["freq"] for r in result}


def clear_existing_concepts(session):
    """기존 Concept 노드 및 MENTIONS 관계 삭제"""
    result = session.run("""
        MATCH (c:Concept)
        DETACH DELETE c
        RETURN count(c) AS deleted
    """)
    deleted = result.single()["deleted"]
    if deleted:
        print(f"  기존 Concept {deleted}개 삭제")


def create_constraints(session):
    """Concept 유니크 제약 생성"""
    try:
        session.run("""
            CREATE CONSTRAINT concept_name IF NOT EXISTS
            FOR (c:Concept) REQUIRE c.name IS UNIQUE
        """)
    except Exception:
        pass


def create_concept_nodes(session, tag_freq):
    """Concept 노드 생성 (MIN_FREQUENCY 이상 태그만)"""
    created = 0
    skipped = 0
    unclassified = []

    for tag, freq in tag_freq.items():
        if not tag or not tag.strip():
            continue

        # 빈도 임계값 미만은 건너뜀
        if freq < MIN_FREQUENCY:
            skipped += 1
            continue

        domain, ctype = CONCEPT_META.get(tag, ("기타", "업무개념"))

        if domain == "기타":
            unclassified.append((tag, freq))

        session.run("""
            MERGE (c:Concept {name: $name})
            SET c.domain    = $domain,
                c.type      = $type,
                c.frequency = $freq
        """, name=tag, domain=domain, type=ctype, freq=freq)
        created += 1

    print(f"  → 빈도 {MIN_FREQUENCY}회 미만 태그 {skipped:,}개 제외")
    return created, unclassified


def create_mentions_edges(session):
    """(QA)-[:MENTIONS]->(Concept) 관계 생성"""
    result = session.run("""
        MATCH (q:QA)
        WHERE q.tags IS NOT NULL AND size(q.tags) > 0
        UNWIND q.tags AS tag
        MATCH (c:Concept {name: tag})
        MERGE (q)-[r:MENTIONS]->(c)
        RETURN count(r) AS cnt
    """)
    return result.single()["cnt"]


def verify(session):
    """결과 검증"""
    stats = session.run("""
        MATCH (c:Concept)
        RETURN
            count(c) AS total,
            count(DISTINCT c.domain) AS domains
    """).single()

    domain_stats = session.run("""
        MATCH (c:Concept)
        RETURN c.domain AS domain,
               count(c) AS concepts,
               sum(c.frequency) AS total_freq
        ORDER BY total_freq DESC
    """).data()

    type_stats = session.run("""
        MATCH (c:Concept)
        RETURN c.type AS type, count(c) AS cnt
        ORDER BY cnt DESC
    """).data()

    edge_cnt = session.run("""
        MATCH ()-[r:MENTIONS]->()
        RETURN count(r) AS cnt
    """).single()["cnt"]

    print(f"\n  Concept 노드 : {stats['total']:,}개 ({stats['domains']}개 도메인)")
    print(f"  MENTIONS 관계: {edge_cnt:,}개\n")

    print(f"  {'도메인':<12} {'개념 수':>6}  {'태그 빈도 합':>10}")
    print(f"  {'-'*12} {'-'*6}  {'-'*10}")
    for d in domain_stats:
        print(f"  {d['domain']:<12} {d['concepts']:>6}  {d['total_freq']:>10,}")

    print(f"\n  {'유형':<10} {'수':>6}")
    print(f"  {'-'*10} {'-'*6}")
    for t in type_stats:
        print(f"  {t['type']:<10} {t['cnt']:>6}")


def main():
    print("=" * 60)
    print("  XPERP Concept 노드 생성")
    print("=" * 60)

    driver = neo4j.GraphDatabase.driver(NEO4J_URI, auth=("neo4j", NEO4J_PASSWORD))
    try:
        driver.verify_connectivity()
        print("✅ Neo4j 연결 성공\n")
    except Exception as e:
        print(f"❌ Neo4j 연결 실패: {e}")
        return

    with driver.session() as session:
        # 1. 기존 정리
        print("🗑️  기존 Concept 노드 정리...")
        clear_existing_concepts(session)
        create_constraints(session)

        # 2. 태그 빈도 조회
        print("📥 태그 빈도 집계 중...")
        tag_freq = fetch_tag_frequencies(session)
        print(f"  → 고유 태그 {len(tag_freq):,}개\n")

        # 3. Concept 노드 생성
        print("📌 Concept 노드 생성 중...")
        created, unclassified = create_concept_nodes(session, tag_freq)
        print(f"  → {created:,}개 Concept 노드 생성 완료")

        classified = created - len(unclassified)
        print(f"  → 분류 완료: {classified}개 / 기타(미분류): {len(unclassified)}개\n")

        # 4. MENTIONS 관계 생성
        print("🔗 (QA)-[:MENTIONS]->(Concept) 관계 생성 중...")
        edge_cnt = create_mentions_edges(session)
        print(f"  → {edge_cnt:,}개 관계 생성 완료\n")

        # 5. 미분류 태그 출력 (빈도 5 이상만)
        notable_unclassified = [(t, f) for t, f in unclassified if f >= 5]
        if notable_unclassified:
            print(f"⚠️  미분류 태그 중 빈도 5회 이상 ({len(notable_unclassified)}개):")
            for tag, freq in sorted(notable_unclassified, key=lambda x: -x[1])[:20]:
                print(f"  {tag:<25} {freq}회")
            print()

        # 6. 검증
        print("📊 최종 결과:")
        verify(session)

    driver.close()
    print("\n🎉 Concept 노드 생성 완료!")
    print("   그래프 시각화에서 Concept 노드를 확인하세요.")


if __name__ == "__main__":
    main()
